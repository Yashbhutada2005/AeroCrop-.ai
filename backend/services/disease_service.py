from __future__ import annotations
from dataclasses import dataclass, field
from typing import ClassVar


@dataclass
class DiseaseInfo:
    class_idx:   int
    name:        str
    crop:        str
    is_healthy:  bool
    chemical_treatment: list[str] = field(default_factory=list)
    organic_treatment:  list[str] = field(default_factory=list)
    severity:    str = "None"  # None | Low | Moderate | High | Critical
    description: str = ""
    chemical_cost: str = ""
    organic_cost:  str = ""

    @property
    def chemical_cost_display(self) -> str:
        if self.chemical_cost:
            return self.chemical_cost
        return DiseaseService.estimate_chemical_cost(self)

    @property
    def organic_cost_display(self) -> str:
        if self.organic_cost:
            return self.organic_cost
        return DiseaseService.estimate_organic_cost(self)


