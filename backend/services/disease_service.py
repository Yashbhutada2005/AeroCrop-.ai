    # Fast lookup dict
    _by_idx: ClassVar[dict[int, DiseaseInfo]] = {}

    @classmethod
    def _ensure_index(cls):
        if not cls._by_idx:
            cls._by_idx = {d.class_idx: d for d in cls.DISEASES}

    @classmethod
    def get_by_index(cls, idx: int) -> DiseaseInfo | None:
        cls._ensure_index()
        if idx in cls._by_idx:
            return cls._by_idx[idx]
        # Dynamic fallback for safety
        if 0 <= idx < len(cls.DISEASES):
            return cls.DISEASES[idx]
        return None

    @classmethod
    def get_all_names(cls) -> list[str]:
        return [d.name for d in cls.DISEASES]

    @classmethod
    def get_class_count(cls) -> int:
        return len(cls.DISEASES)

    @classmethod
    def estimate_chemical_cost(cls, d: DiseaseInfo | None) -> str:
        """Estimate realistic market treatment cost in ₹/Acre per application for Maharashtra."""
        if not d or d.is_healthy or not d.chemical_treatment:
            return "₹0 / Acre (None required)"
        cond_lower = d.name.lower()
        if any(k in cond_lower for k in ["armyworm", "army_worm", "caterpillar", "borer", "dead_heart"]):
            return "₹850 – ₹1,300 / Acre"
        if any(k in cond_lower for k in ["wilt", "fusarium", "rhizome_rot", "pink_rot", "panama", "moko"]):
            return "₹700 – ₹1,100 / Acre"
        if any(k in cond_lower for k in ["late_blight", "blast", "anthracnose"]):
            return "₹650 – ₹950 / Acre"
        if any(k in cond_lower for k in ["rust", "smut", "mildew"]):
            return "₹500 – ₹800 / Acre"
        if any(k in cond_lower for k in ["aphid", "jassid", "whitefly", "thrips", "mite", "mealybug"]):
            return "₹450 – ₹700 / Acre"
        if any(k in cond_lower for k in ["virus", "mosaic", "curl", "streak"]):
            return "₹450 – ₹700 / Acre"
        if d.severity == "Critical":
            return "₹750 – ₹1,200 / Acre"
        if d.severity == "High":
            return "₹600 – ₹900 / Acre"
        return "₹450 – ₹750 / Acre"

